export function mergeDemoPromotions(apiPromotions: PublicPromotion[]): PublicPromotion[] {
  const merged = [...apiPromotions]
  const demoAll = [...DEMO_NEARBY_PROMOTIONS, DEMO_FAR_PROMOTION]

  for (const demo of demoAll) {
    if (!merged.some((promotion) => promotion.id === demo.id)) {
      merged.push(demo)
    }
  }

  return merged
}

export function mergeDemoReservationCounts(counts: Record<string, number>): Record<string, number> {
  return { ...counts, ...DEMO_PROMOTION_RESERVATION_COUNTS }
}
