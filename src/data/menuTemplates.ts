export const DEFAULT_MENU_BACKGROUND_IMAGE_OPACITY = 22

export function normalizeMenuBackgroundImageOpacity(value: unknown): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    return DEFAULT_MENU_BACKGROUND_IMAGE_OPACITY
  }

  return Math.min(100, Math.max(0, Math.round(value)))
}

